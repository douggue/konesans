#!/usr/bin/env node
/**
 * Bundle real flag artwork for every country in packages/core/src/content/world.ts.
 * Source: flag-icons (MIT, https://github.com/lipis/flag-icons), 4:3 SVGs, minified with svgo.
 *
 *   mkdir -p /tmp/fl && cd /tmp/fl && npm i flag-icons@7.2.3 svgo@3.3.2
 *   NODE_PATH=/tmp/fl/node_modules node tools/gen-flags.mjs
 *
 * Writes apps/mobile/src/ui/flags.ts (iso -> svg string).
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { createRequire } from 'node:module';
import { join } from 'node:path';

const ROOT = new URL('../', import.meta.url).pathname;
const require = createRequire(join(process.env.NODE_PATH ?? ROOT, 'x.js'));
const { optimize } = require('svgo');
const FLAGS = join(require.resolve('flag-icons/package.json'), '..', 'flags', '4x3');

const world = readFileSync(join(ROOT, 'packages/core/src/content/world.ts'), 'utf8');
const isos = [...world.matchAll(/^\s*\['([A-Z]{2})',/gm)].map((m) => m[1]);
if (isos.length < 150) throw new Error('could not read ISO codes from world.ts (' + isos.length + ')');

const out = {};
let raw = 0, min = 0;
const missing = [];
for (const iso of [...new Set(isos)].sort()) {
  const p = join(FLAGS, iso.toLowerCase() + '.svg');
  if (!existsSync(p)) { missing.push(iso); continue; }
  const src = readFileSync(p, 'utf8');
  raw += src.length;
  const res = optimize(src, {
    multipass: true,
    floatPrecision: 1,
    plugins: [
      { name: 'preset-default', params: { overrides: { removeViewBox: false } } },
      { name: 'prefixIds', params: { prefix: 'f' + iso.toLowerCase() } }, // unique ids when several flags share a screen
      'removeDimensions',
    ],
  });
  out[iso] = res.data;
  min += res.data.length;
}
const big = Object.entries(out).sort((a, b) => b[1].length - a[1].length).slice(0, 8).map(([k, v]) => `${k} ${(v.length / 1024).toFixed(0)}K`);
const ts = `/* Generated by tools/gen-flags.mjs from flag-icons 7.2.3 (MIT © 2013 Panayiotis Lipiridis). Do not edit by hand. */
/** Real flag artwork (4:3 SVG) for every country in the world table. */
export const FLAG_SVG: Record<string, string> = ${JSON.stringify(out).replace(/","/g, '",\n"')};
`;
writeFileSync(join(ROOT, 'apps/mobile/src/ui/flags.ts'), ts);
console.log(`flags: ${Object.keys(out).length} written, missing ${missing.join(',') || 'none'}; ${(raw / 1024).toFixed(0)} KB → ${(min / 1024).toFixed(0)} KB`);
console.log('largest:', big.join(', '));
