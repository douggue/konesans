#!/usr/bin/env node
/**
 * Bundle the course illustrations (design/illustrations/svg/*.svg) into apps/mobile/src/ui/illustrations.ts
 * (id → minified SVG string, rendered with react-native-svg SvgXml). Run after adding or editing a drawing.
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
const ROOT = new URL('../', import.meta.url).pathname;
const DIR = ROOT + 'design/illustrations/svg/';
const out = {};
let bytes = 0;
for (const f of readdirSync(DIR).filter((f) => f.endsWith('.svg')).sort()) {
  let s = readFileSync(DIR + f, 'utf8')
    .replace(/<\?xml[^>]*>/g, '').replace(/<!--[\s\S]*?-->/g, '')
    .replace(/\s+/g, ' ').replace(/>\s+</g, '><').trim();
  if (!/^<svg[^>]*viewBox="0 0 96 96"/.test(s)) throw new Error(`${f}: must start with <svg … viewBox="0 0 96 96">`);
  if (/<(script|image|foreignObject|style)\b|href=/.test(s)) throw new Error(`${f}: scripts, images, styles and links are not allowed`);
  out[f.slice(0, -4)] = s;
  bytes += s.length;
}
writeFileSync(ROOT + 'apps/mobile/src/ui/illustrations.ts',
  `/* Generated by tools/gen-illustrations.mjs from design/illustrations/svg — do not edit by hand. */\n` +
  `/** Konesans course pictures and unit badges (${Object.keys(out).length}), viewBox 0 0 96 96. */\n` +
  `export const ILLUSTRATIONS: Record<string, string> = ${JSON.stringify(out, null, 0).replace(/","/g, '",\n"')};\n`);
console.log(`illustrations: ${Object.keys(out).length} (${Math.round(bytes / 1024)} KB)`);
