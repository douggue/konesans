#!/usr/bin/env node
/**
 * Expand the compact authored bank (content/bank/*.json) into:
 *   packages/core/src/content/bank.ts  — the questions the app ships
 *   apps/admin/bank.json               — the same, for the admin panel
 * Run after editing content/bank or after tools/sync-bank.mjs.
 */
import { readdirSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { join, basename } from 'node:path';

const ROOT = new URL('../', import.meta.url).pathname;
const DIR = join(ROOT, 'content/bank');
const CATS = ['istwa', 'jewografi', 'peyi', 'kilti', 'syans', 'matematik', 'jeneral', 'espo', 'teknoloji'];

export function expand(q, category) {
  return {
    id: q.id, category, difficulty: q.d, ages: q.ages,
    prompt: { ht: q.ht, fr: q.fr },
    options: q.opts.map((ht, i) => ({ ht, fr: q.optsFr?.[i] ?? ht })),
    answer: q.a,
    explain: q.ex ? { ht: q.ex, fr: q.exFr ?? q.ex } : undefined,
    status: q.status ?? 'review',
    topic: q.topic, note: q.note || undefined,
  };
}

export function loadBank() {
  const out = [];
  for (const f of readdirSync(DIR).filter((f) => f.endsWith('.json')).sort()) {
    const cat = basename(f, '.json').split('.')[0];
    if (!CATS.includes(cat)) continue;
    for (const q of JSON.parse(readFileSync(join(DIR, f), 'utf8'))) out.push(expand(q, cat));
  }
  return out;
}

const bank = loadBank();
const counts = {};
for (const q of bank) counts[q.category] = (counts[q.category] ?? 0) + 1;

// A JSON string + JSON.parse: a 2,000-item object literal is too big for TypeScript to type (TS2590)
// and JSON.parse is also faster to load on phones than the same data as JS source.
const ts = `/* Generated by tools/build-bank.mjs from content/bank/*.json — do not edit by hand. */
import type { Question } from '../types.js';

/** Authored question bank (${bank.length} questions). Proofread in the admin panel; see content/bank/BRIEF.md. */
export const BANK: Question[] = JSON.parse(${JSON.stringify(JSON.stringify(bank))});
`;
writeFileSync(join(ROOT, 'packages/core/src/content/bank.ts'), ts);
mkdirSync(join(ROOT, 'apps/admin'), { recursive: true });
writeFileSync(join(ROOT, 'apps/admin/bank.json'), JSON.stringify({ generatedAt: new Date().toISOString(), counts, questions: bank }));
console.log(`bank: ${bank.length} questions`, counts);
