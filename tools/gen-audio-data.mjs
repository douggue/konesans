// Bundles the app's sounds as data: URIs (apps/mobile/src/lib/audio-data.ts).
// Why: on Android, bundled sound *files* weren't reachable after over-the-air updates (players never loaded,
// ExpoAsset.downloadAsync failed). The audio players (ExoPlayer / <audio>) play data: URIs directly.
// Run after changing anything in apps/mobile/assets/audio:  node tools/gen-audio-data.mjs
import fs from 'node:fs'; import path from 'node:path';
const DIR = 'apps/mobile/assets/audio';
const OUT = 'apps/mobile/src/lib/audio-data.ts';
const files = fs.readdirSync(DIR).filter((f) => /\.(mp3|m4a)$/.test(f)).sort();
let o = '// Generated by tools/gen-audio-data.mjs — do not edit. Original sounds: design/audio (see LICENSES.md).\n/* eslint-disable */\nexport const AUDIO_DATA: Record<string, string> = {\n';
let total = 0;
for (const f of files) {
  const b = fs.readFileSync(path.join(DIR, f)); total += b.length;
  const mime = f.endsWith('.mp3') ? 'audio/mpeg' : 'audio/mp4';
  o += `  ${JSON.stringify(f.replace(/\.(mp3|m4a)$/, ''))}: 'data:${mime};base64,${b.toString('base64')}',\n`;
}
o += '};\n';
fs.writeFileSync(OUT, o);
console.log(`${files.length} sounds, ${(total / 1024).toFixed(0)} KB → ${OUT} (${(o.length / 1024).toFixed(0)} KB)`);
