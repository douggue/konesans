#!/usr/bin/env node
/** Extract the app's UI strings (apps/mobile/src/lib/i18n.ts) into server/nakama/src/strings.gen.ts so the admin can show and override them. */
import { readFileSync, writeFileSync, readdirSync, existsSync } from 'node:fs';
const ROOT = new URL('../', import.meta.url).pathname;
const src = readFileSync(ROOT + 'apps/mobile/src/lib/i18n.ts', 'utf8');
const m = src.match(/const S = \{([\s\S]*?)\n\} as const;/);
if (!m) throw new Error('could not find `const S = {...} as const` in i18n.ts');
// Feature string files (src/lib/strings/*.ts) are spread into S: `...QUESTS_STRINGS,`
const extra = {};
const dir = ROOT + 'apps/mobile/src/lib/strings/';
if (existsSync(dir)) for (const f of readdirSync(dir).filter((x) => x.endsWith('.ts'))) {
  const txt = readFileSync(dir + f, 'utf8');
  for (const mm of txt.matchAll(/export const (\w+)\s*=\s*\{([\s\S]*?)\n\}\s*as const;/g)) extra[mm[1]] = new Function(`return {${mm[2]}}`)();
}
const S = new Function(...Object.keys(extra), `return {${m[1]}}`)(...Object.values(extra));
writeFileSync(ROOT + 'server/nakama/src/strings.gen.ts',
  `/* Generated by tools/gen-strings.mjs from apps/mobile/src/lib/i18n.ts — do not edit. */\nexport const STRING_DEFAULTS: Record<string, [string, string]> = ${JSON.stringify(S, null, 0)};\n`);
console.log(`strings: ${Object.keys(S).length} keys`);
