import * as Speech from 'expo-speech';
import * as Haptics from 'expo-haptics';
import { Platform } from 'react-native';
import { useStore } from './store';
import { AppState } from 'react-native';
import { createAudioPlayer, setAudioModeAsync, type AudioPlayer } from 'expo-audio';
import { AUDIO_DATA } from './audio-data';

const VOICE_LANG: Record<string, string> = { en: 'en-US', es: 'es-MX', fr: 'fr-FR', ht: 'fr-HT' };

/** Speak an audio ref (`tts:<lang>:<text>`) or plain text in the given language. */
export function speak(refOrText: string, lang = 'ht') {
  if (!useStore.getState().settings.voice) return;
  let text = refOrText, l = lang;
  const m = /^tts:([a-z]{2}):([\s\S]+)$/.exec(refOrText);
  if (m) { l = m[1]; text = m[2]; }
  try { Speech.stop(); Speech.speak(text, { language: VOICE_LANG[l] ?? l, rate: 0.9 }); } catch { /* no TTS on this device */ }
}

export function tap(kind: 'light' | 'success' | 'error' = 'light') {
  if (!useStore.getState().settings.haptic || Platform.OS === 'web') return;
  try {
    if (kind === 'light') Haptics.impactAsync(Haptics.ImpactFeedbackStyle.Light);
    else Haptics.notificationAsync(kind === 'success' ? Haptics.NotificationFeedbackType.Success : Haptics.NotificationFeedbackType.Error);
  } catch { /* ignore */ }
}

// ─── Sound effects + music (expo-audio) ──────────────────────────────────────
// Assets are original, generated by design/audio/build.py. Every function below is fire-and-forget
// and never throws: no audio (web before a tap, missing native module, odd device) just means silence.

const SFX_SRC = {
  tap: 'sfx_tap',
  correct: 'sfx_correct',
  wrong: 'sfx_wrong',
  combo: 'sfx_combo',
  tick: 'sfx_tick',
  timeup: 'sfx_timeup',
  vs: 'sfx_vs',
  found: 'sfx_found',
  ping: 'sfx_ping',
  pop: 'sfx_pop',
  win: 'sfx_win',
  lose: 'sfx_lose',
  draw: 'sfx_draw',
  coin: 'sfx_coin',
  badge: 'sfx_badge',
  level: 'sfx_level',
  // duel reaction stickers (src/ui/Reactions.tsx)
  re_bravo: 'sfx_re_bravo',
  re_byen_jwe: 'sfx_re_byen_jwe',
  re_wow: 'sfx_re_wow',
  re_dife: 'sfx_re_dife',
  re_ri: 'sfx_re_ri',
  re_ke: 'sfx_re_ke',
  re_bon_chans: 'sfx_re_bon_chans',
  re_anko: 'sfx_re_anko',
  re_mwen_pare: 'sfx_re_mwen_pare',
} as const;
export type SfxName = keyof typeof SFX_SRC;

const MUSIC_SRC = {
  menu: 'menu',
  duel_search: 'duel_search',
  duel_battle: 'duel_battle',
  duel_hurry: 'duel_hurry',
} as const;
type Loop = keyof typeof MUSIC_SRC;
export type MusicTrack = Exclude<Loop, 'duel_hurry'>;

/** Long result stings (ms), so the trophy jingle doesn't land on top of them. */
const STING_MS: Partial<Record<SfxName, number>> = { win: 2600, lose: 2200, draw: 1300, level: 1800 };

/** Effects volume (0–1). Kept soft so kids can concentrate; small UI ticks even softer. */
const SFX_VOL: Partial<Record<SfxName, number>> = { tap: 0.25, tick: 0.35, pop: 0.35, ping: 0.35,
  re_bravo: 0.35, re_byen_jwe: 0.35, re_wow: 0.35, re_dife: 0.35, re_ri: 0.35, re_ke: 0.35, re_bon_chans: 0.35, re_anko: 0.35, re_mwen_pare: 0.35 };

/** Music sits under SFX and the voice; while TTS talks it ducks further. */
const MUSIC_VOL = 0.28; // quiet bed under the game (owner: 'too loud')
const DUCK_VOL = 0.3;

interface Chan { p: AudioPlayer; vol: number; target: number; rate: number; playing: boolean }
interface Engine {
  sfx: Partial<Record<SfxName, AudioPlayer>>;
  chans: Partial<Record<Loop, Chan>>;
  want: MusicTrack | null;
  hurry: boolean;
  fresh: Set<Loop>;
  duck: number; duckTarget: number;
  fade: ReturnType<typeof setInterval> | null;
  poll: ReturnType<typeof setInterval> | null;
  active: boolean;
  ready: boolean;
  /** a result sting is playing until then (ms) — the trophy jingle waits for it */
  busyUntil: number;
}
// Kept on globalThis so Fast Refresh in dev reuses the players instead of leaking new ones.
const G = globalThis as unknown as { __ksAudio?: Engine };
const E: Engine = G.__ksAudio ?? (G.__ksAudio = {
  sfx: {}, chans: {}, want: null, hurry: false, fresh: new Set(), duck: 1, duckTarget: 1, fade: null, poll: null,
  active: AppState.currentState !== 'background', ready: false, busyUntil: 0,
});

/** First audio error seen (shown small in Settings so a silent phone can be diagnosed). */
export let audioError = '';
const safe = (f: () => void) => { try { f(); } catch (e: any) { if (!audioError) audioError = String(e?.message ?? e).slice(0, 160); /* audio is best-effort */ } };
/** Read the app state live: on Android the JS can start while the app still reports 'background', and the
 *  'active' change may fire before our listener exists — a cached flag then stays false and everything is silent. */
const appActive = () => AppState.currentState !== 'background';

/** Which source each player got (for the sound test). */
const SRC_URI: Record<string, string> = {};
/**
 * Make a player for one of our sounds. The sounds are embedded as data: URIs (src/lib/audio-data.ts,
 * tools/gen-audio-data.mjs): bundled sound *files* weren't reachable on Android after over-the-air updates.
 */
function makePlayer(key: string, tag: string): AudioPlayer {
  const uri = AUDIO_DATA[key];
  SRC_URI[tag] = uri ? `data ${Math.round(uri.length / 1024)}KB` : 'missing';
  return createAudioPlayer(uri ? { uri } : null, { updateInterval: 1000 });
}

function init() {
  if (E.ready) return;
  E.ready = true;
  safe(() => { setAudioModeAsync({ playsInSilentMode: true, interruptionMode: 'mixWithOthers', shouldPlayInBackground: false }).catch(() => {}); });
  // Preload every SFX now so the first play has no load latency.
  for (const k of Object.keys(SFX_SRC) as SfxName[]) safe(() => { if (!E.sfx[k]) E.sfx[k] = makePlayer(SFX_SRC[k], k); });
  // Load the music loops too: on Android a player ignores play() until its file has loaded.
  for (const k of Object.keys(MUSIC_SRC) as Loop[]) safe(() => { chan(k); });
  // Watchdog: anything that should be sounding but isn't (play() came before the file loaded, audio focus
  // was taken by another app, …) gets started again.
  setInterval(() => safe(() => {
    for (const c of Object.values(E.chans)) {
      if (c && c.playing && c.vol > 0 && c.p.isLoaded && !c.p.playing) safe(() => c.p.play());
    }
    // music wanted but nothing running (e.g. the wish came before settings finished loading) → start it
    const st = useStore.getState();
    if (E.want && st.hydrated && st.settings.music && appActive() && !Object.values(E.chans).some((c) => c?.playing)) apply(0.4);
  }), 700);
  safe(() => {
    AppState.addEventListener('change', (st) => { E.active = st !== 'background'; apply(0); });
    // live settings + trophy jingle (read-only use of the store)
    useStore.subscribe((s, prev) => {
      if (s.settings.music !== prev.settings.music || s.hydrated !== prev.hydrated) apply(s.settings.music ? 0.4 : 0);
      if (s.newBadges.length > prev.newBadges.length) setTimeout(() => sfx('badge'), Math.max(700, E.busyUntil - Date.now() + 150));
    });
  });
  // Web: browsers block audio until the first tap/key — retry whatever should be playing then.
  if (Platform.OS === 'web') safe(() => {
    const unlock = () => { for (const c of Object.values(E.chans)) if (c?.playing && !c.p.playing) safe(() => c.p.play()); };
    document.addEventListener('pointerdown', unlock, true);
    document.addEventListener('keydown', unlock, true);
  });
}

/** Play a one-shot sound effect (respects Settings → sound effects). */
export function sfx(name: SfxName) {
  safe(() => {
    if (!useStore.getState().settings.sfx || !appActive()) return;
    init();
    const p = E.sfx[name] ?? (E.sfx[name] = makePlayer(SFX_SRC[name], name));
    p.volume = SFX_VOL[name] ?? 0.45;
    if (STING_MS[name]) E.busyUntil = Date.now() + STING_MS[name]!;
    if (!p.isLoaded) { // first use right after start: play as soon as the file is ready (give up after 2 s)
      const t0 = Date.now();
      const id = setInterval(() => safe(() => { if (p.isLoaded) { clearInterval(id); p.play(); } else if (Date.now() - t0 > 2000) clearInterval(id); }), 60);
      return;
    }
    if (p.playing || p.currentTime > 0) p.seekTo(0).catch(() => {});
    p.play();
  });
}

/** Which feedback sound an answer gets, from the run of results so far (latest last):
 *  right → 'correct' (every 3rd right in a row → 'combo'); wrong → 'wrong'; ran out of time → 'timeup'. */
export function answerSfx(results: boolean[], timedOut = false): SfxName {
  if (!results[results.length - 1]) return timedOut ? 'timeup' : 'wrong';
  let run = 0;
  for (let k = results.length - 1; k >= 0 && results[k]; k--) run++;
  return run >= 3 && run % 3 === 0 ? 'combo' : 'correct';
}

/** Switch the background loop (crossfades); `null` fades the music out. Respects Settings → music. */
export function music(track: MusicTrack | null) {
  safe(() => {
    init();
    if (track === E.want) return;
    if (track) E.fresh.add(track);
    E.want = track;
    E.hurry = false;
    apply(0.6);
  });
}

/** Duel only: 'hurry' crossfades duel_battle into the faster-feeling duel_hurry loop; 'normal' brings it back. */
export function musicIntensity(level: 'hurry' | 'normal') {
  safe(() => {
    const h = level === 'hurry';
    if (h === E.hurry) return;
    E.hurry = h;
    if (h) E.fresh.add('duel_hurry');
    apply(h ? 0.25 : 0.4);
  });
}

/** One line describing the audio engine's state, for the sound test button in Settings. */
export async function audioTest(): Promise<string> {
  sfx('correct');
  await new Promise((r) => setTimeout(r, 700));
  const st = useStore.getState();
  const p = E.sfx.correct as any;
  const m = E.chans.menu as any;
  const parts = [
    `app=${AppState.currentState}`, `sfx=${st.settings.sfx ? 1 : 0}`, `music=${st.settings.music ? 1 : 0}`, `hyd=${st.hydrated ? 1 : 0}`,
    `ready=${E.ready ? 1 : 0}`, `want=${E.want ?? '-'}`,
    p ? `ding: loaded=${p.isLoaded ? 1 : 0} play=${p.playing ? 1 : 0} dur=${Math.round((p.duration ?? 0) * 100) / 100} t=${Math.round((p.currentTime ?? 0) * 100) / 100} vol=${p.volume} mute=${p.muted ? 1 : 0}` : 'ding: none',
    m ? `menu: loaded=${m.p.isLoaded ? 1 : 0} play=${m.p.playing ? 1 : 0} vol=${Math.round((m.p.volume ?? 0) * 100) / 100} on=${m.playing ? 1 : 0}` : 'menu: none',
    `src=${(SRC_URI.correct ?? '-').slice(0, 90)}`,
    audioError ? `err=${audioError}` : '',
  ];
  return parts.filter(Boolean).join(' · ');
}

/** Warm up the players (optional; the first sfx()/music() call does it too). */
export function preloadAudio() { safe(init); }

function chan(k: Loop): Chan {
  let c = E.chans[k];
  if (!c) {
    const p = makePlayer(MUSIC_SRC[k], k);
    p.loop = true;
    p.volume = 0;
    c = E.chans[k] = { p, vol: 0, target: 0, rate: 1, playing: false };
  }
  return c;
}

/** Bring the players in line with what should be sounding. `fade` = seconds (0 = at once). */
function apply(fade: number) {
  safe(() => {
    const st = useStore.getState();
    const on = st.hydrated && st.settings.music && appActive();
    const want: Loop | null = !on || !E.want ? null : E.want === 'duel_battle' && E.hurry ? 'duel_hurry' : E.want;
    for (const k of Object.keys(E.chans) as Loop[]) {
      const c = E.chans[k]!;
      if (k === want) continue;
      c.target = 0;
      if (fade <= 0 || !c.playing) { c.vol = 0; if (c.playing) safe(() => c.p.pause()); c.playing = false; safe(() => { c.p.volume = 0; }); }
      else c.rate = 1 / fade;
    }
    if (want) {
      const c = chan(want);
      if (!c.playing) {
        if (E.fresh.has(want)) { E.fresh.delete(want); if (c.p.isLoaded) safe(() => { c.p.seekTo(0).catch(() => {}); }); }
        c.vol = fade <= 0 ? 1 : 0;
        safe(() => { c.p.volume = c.vol * MUSIC_VOL * E.duck; c.p.play(); });
        c.playing = true;
      }
      c.target = 1;
      c.rate = 1 / Math.max(fade, 0.05);
    }
    ensureTimers();
  });
}

function ensureTimers() {
  const moving = Object.values(E.chans).some((c) => c && c.vol !== c.target) || E.duck !== E.duckTarget;
  if (moving && !E.fade) E.fade = setInterval(step, 33);
  const playing = Object.values(E.chans).some((c) => c?.playing);
  const listen = playing && useStore.getState().settings.voice;
  if (listen && !E.poll) E.poll = setInterval(pollSpeech, 300);
  if (!listen && E.poll) { clearInterval(E.poll); E.poll = null; E.duckTarget = 1; }
}

function pollSpeech() {
  safe(() => {
    Speech.isSpeakingAsync().then((talking) => {
      const t = talking ? DUCK_VOL : 1;
      if (t !== E.duckTarget) { E.duckTarget = t; ensureTimers(); }
    }).catch(() => {});
  });
}

function step() {
  safe(() => {
    const dt = 0.033;
    if (E.duck !== E.duckTarget) {
      const r = (E.duckTarget < E.duck ? 5 : 1.5) * dt; // duck fast, recover gently
      E.duck = E.duck < E.duckTarget ? Math.min(E.duckTarget, E.duck + r) : Math.max(E.duckTarget, E.duck - r);
    }
    let moving = E.duck !== E.duckTarget;
    for (const c of Object.values(E.chans)) {
      if (!c) continue;
      if (c.vol !== c.target) {
        const r = c.rate * dt;
        c.vol = c.vol < c.target ? Math.min(c.target, c.vol + r) : Math.max(c.target, c.vol - r);
        moving = moving || c.vol !== c.target;
      }
      if (c.playing && c.vol <= 0 && c.target <= 0) { c.playing = false; safe(() => c.p.pause()); }
      // equal-power-ish curve so crossfades don't dip
      if (c.playing) safe(() => { c.p.volume = Math.sin((c.vol * Math.PI) / 2) * MUSIC_VOL * E.duck; });
    }
    if (!moving && E.fade) { clearInterval(E.fade); E.fade = null; }
    ensureTimers();
  });
}

